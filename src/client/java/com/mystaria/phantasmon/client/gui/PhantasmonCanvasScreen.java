	/** Nickname if set, else Cobblemon's localized species name, else the raw id capitalized. Public: also used for chat summaries. */
	public static String displayName(PokemonDto pokemon) {
		Object nickname = pokemon.data() == null ? null : pokemon.data().get("nickname");
		if (nickname != null && !nickname.toString().isBlank()) {
			return nickname.toString();
		}
		Species species = PokemonSpecies.INSTANCE.getByName(pokemon.species());
		if (species != null) {
			return species.getTranslatedName().getString();
		}
		String id = pokemon.species() == null ? "?" : pokemon.species();
		return id.isEmpty() ? id : id.substring(0, 1).toUpperCase(Locale.ROOT) + id.substring(1);
	}


	/** Screen pixels per canvas px (≈0.8-1 at usual resolutions/GUI scales, never an integer in general). */
	protected float pixelsPerCanvasPx() {
		return (float) (scale * Minecraft.getInstance().getWindow().getGuiScale());
	}

	/**
	 * Thickness, in canvas px, of a line that always covers at least one
	 * screen pixel. A literal 1 px canvas line is &lt;1 screen pixel wide once
	 * the canvas is scaled down, and the rasterizer then drops it depending on
	 * where it falls — that's what made whole panel edges and slot borders
	 * disappear on Adrien's first PC capture (2026-10-02).
	 */
	protected int hairline() {
		float ppx = pixelsPerCanvasPx();
		return ppx <= 0 ? 1 : Math.max(1, (int) Math.ceil(1f / ppx - 0.01f));
	}

	/** Rectangle border drawn with {@link #hairline()}-thick edges (replaces {@code GuiGraphics.renderOutline}). */
	protected void outline(GuiGraphics g, int x, int y, int w, int h, int color) {
		int t = hairline();
		g.fill(x, y, x + w, y + t, color);
		g.fill(x, y + h - t, x + w, y + h, color);
		g.fill(x, y + t, x + t, y + h - t, color);
		g.fill(x + w - t, y + t, x + w, y + h - t, color);
	}

	/** Approximates a CSS outer {@code box-shadow} glow with fading rings. */
	protected void glowOutside(GuiGraphics g, int x, int y, int w, int h, int rgb, float alpha, int size) {
		int t = hairline();
		for (int i = t; i <= size; i += t) {
			float falloff = 1f - (i - t) / (float) size;
			outline(g, x - i, y - i, w + 2 * i, h + 2 * i, argb(rgb, alpha * falloff * falloff));
		}
	}

	/** Same for an {@code inset} glow (selected slot). */
	protected void glowInside(GuiGraphics g, int x, int y, int w, int h, int rgb, float alpha, int size) {
		int t = hairline();
		for (int i = t; i <= size; i += t) {
			float falloff = 1f - (i - t) / (float) size;
			outline(g, x + i, y + i, w - 2 * i, h - 2 * i, argb(rgb, alpha * falloff * falloff));
		}
	}


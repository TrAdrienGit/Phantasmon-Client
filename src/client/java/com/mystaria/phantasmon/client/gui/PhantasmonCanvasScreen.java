	protected void renderWorldBackdrop(GuiGraphics graphics, int mouseX, int mouseY, float partialTick) {
		super.renderBackground(graphics, mouseX, mouseY, partialTick);
	}

	protected void beginCanvas(GuiGraphics g) {
		line = hairline();
		PoseStack pose = g.pose();
		pose.pushPose();
		pose.translate(originX, originY, 0);
		pose.scale(scale, scale, 1f);
	}

	protected void endCanvas(GuiGraphics g) {
		g.pose().popPose();
	}

	protected double toCanvasX(double guiX) {
		return (guiX - originX) / scale;
	}

	protected double toCanvasY(double guiY) {
		return (guiY - originY) / scale;
	}

	protected static boolean inside(double x, double y, int bx, int by, int bw, int bh) {
		return x >= bx && x < bx + bw && y >= by && y < by + bh;
	}


/**
 * Phantasmon's screen "design system" (Adrien 2026-10-02): everything the
 * live trade screen established — and that the PC screen now reuses so both
 * share one art direction — lives here.
 *
 * <p><b>Coordinates</b>: subclasses lay everything out in the handoff
 * mock-up's own 1600×900 px space ({@code Documentation/design/trade-screen/}). The
 * canvas is drawn through one pose scale of {@code s/2 × MENU_SCALE} GUI
 * units per px, {@code s = min(1, width/800, height/450)} (trade spec §2),
 * centered. Mouse positions go back through {@link #toCanvasX}/{@link #toCanvasY}
 * before any hit test.
 *
 * <p><b>Text</b>: Minecraft's font only stays crisp at integer scales — titles
 * and values use scale 2, small labels scale 1.
 *
 * <p><b>Draw order</b>: in 1.21.1 {@code fill}/{@code drawString} are batched
 * while {@code blit} draws immediately, so a texture blitted after a fill
 * would end up <em>under</em> it. {@link #blitTexture} therefore always
 * {@code flush()}es first, which keeps the code order the visual order.
 * Modal windows are drawn at z=2000, above item icons and 3D models.
 *
 * <p>Gradients/halos the vanilla GUI can't draw are the PNGs generated by
 * {@code scripts/generate_trade_textures.py} from the mock-up's exact CSS.
 */

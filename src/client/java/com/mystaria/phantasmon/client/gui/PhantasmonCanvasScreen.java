	@Override
	protected void init() {
		applyTheme();
		float s = Math.min(1f, Math.min(this.width / 800f, this.height / 450f));
		scale = s / 2f * MENU_SCALE;
		originX = (this.width - CANVAS_W * scale) / 2f;
		originY = (this.height - CANVAS_H * scale) / 2f;
		line = hairline();
	}

	@Override
	public boolean isPauseScreen() {
		return false;
	}


	/**
	 * Font scale actually used for a requested {@code textScale}: snapped so
	 * one font pixel is a whole number of screen pixels (at least one). At a
	 * non-integer ratio, nearest-neighbour sampling drops/duplicates font
	 * columns and small text turns into an unreadable smear (Adrien's PC
	 * capture, 2026-10-02: buttons and the nature +/- text).
	 */
	protected float snapTextScale(float textScale) {
		float ppx = pixelsPerCanvasPx();
		return ppx <= 0 ? textScale : Math.max(1, Math.round(textScale * ppx)) / ppx;
	}

	/** Letter-spacing rounded to whole screen pixels, so every glyph stays on the pixel grid. */
	private float snapSpacing(float spacing) {
		float ppx = pixelsPerCanvasPx();
		return spacing <= 0f || ppx <= 0 ? Math.max(0f, spacing) : Math.round(spacing * ppx) / ppx;
	}

	/** Canvas x → nearest canvas x that lands exactly on a screen pixel. */
	private float snapX(float x) {
		double gui = Minecraft.getInstance().getWindow().getGuiScale();
		return (float) ((Math.round((originX + x * scale) * gui) / gui - originX) / scale);
	}

	private float snapY(float y) {
		double gui = Minecraft.getInstance().getWindow().getGuiScale();
		return (float) ((Math.round((originY + y * scale) * gui) / gui - originY) / scale);
	}

	/** Draws {@code text} with its glyph top at {@code y}, optionally with CSS-like {@code letter-spacing} (canvas px). Pixel-snapped, see {@link #snapTextScale}. */
	protected void drawText(GuiGraphics g, String text, float x, float y, float textScale, int color, boolean bold, float spacing) {
		if (text == null || text.isEmpty() || (color >>> 24) < 8) {
			return;
		}
		float effectiveScale = snapTextScale(textScale);
		float effectiveSpacing = snapSpacing(spacing);
		PoseStack pose = g.pose();
		pose.pushPose();
		pose.translate(snapX(x), snapY(y), 0);
		pose.scale(effectiveScale, effectiveScale, 1f);
		if (effectiveSpacing <= 0f) {
			g.drawString(font, styled(text, bold), 0, 0, color, false);
		} else {
			float cursor = 0f;
			int i = 0;
			while (i < text.length()) {
				int codePoint = text.codePointAt(i);
				String glyph = new String(Character.toChars(codePoint));
				pose.pushPose();
				pose.translate(cursor, 0, 0);
				g.drawString(font, styled(glyph, bold), 0, 0, color, false);
				pose.popPose();
				cursor += font.width(styled(glyph, bold)) + effectiveSpacing / effectiveScale;
				i += Character.charCount(codePoint);
			}
		}
		pose.popPose();
	}

	protected void drawSequence(GuiGraphics g, FormattedCharSequence sequence, float x, float y, int color) {
		float effectiveScale = snapTextScale(1f);
		PoseStack pose = g.pose();
		pose.pushPose();
		pose.translate(snapX(x), snapY(y), 0);
		pose.scale(effectiveScale, effectiveScale, 1f);
		g.drawString(font, sequence, 0, 0, color, false);
		pose.popPose();
	}

	/** Width of a {@link #drawSequence} line, in canvas px. */
	protected float sequenceWidth(FormattedCharSequence sequence) {
		return font.width(sequence) * snapTextScale(1f);
	}

	/** Rendered width in canvas px, letter-spacing included (same snapping as {@link #drawText}). */
	protected float textWidth(String text, float textScale, boolean bold, float spacing) {
		if (text == null || text.isEmpty()) {
			return 0f;
		}
		int glyphs = text.codePointCount(0, text.length());
		// Bold safety margin: some modpack fonts draw bold one font pixel wider per glyph than font.width() reports.
		int boldMargin = bold ? glyphs : 0;
		return (font.width(styled(text, bold)) + boldMargin) * snapTextScale(textScale) + snapSpacing(spacing) * (glyphs - 1);
	}

	/** Truncates with "…" so the text fits in {@code maxWidth} canvas px (no overflowing text). */
	protected String fitText(String text, float maxWidth, float textScale, boolean bold, float spacing) {
		if (text == null || textWidth(text, textScale, bold, spacing) <= maxWidth) {
			return text;
		}
		String ellipsis = "…";
		String result = text;
		while (!result.isEmpty() && textWidth(result + ellipsis, textScale, bold, spacing) > maxWidth) {
			result = result.substring(0, result.length() - 1);
		}
		return result.stripTrailing() + ellipsis;
	}

	protected static MutableComponent styled(String text, boolean bold) {
		MutableComponent component = Component.literal(text);
		return bold ? component.withStyle(ChatFormatting.BOLD) : component;
	}

	protected static String upper(String text) {
		return text == null ? "" : text.toUpperCase(Locale.ROOT);
	}

	protected static String stripPrefix(String message) {
		return message.startsWith("[Phantasmon] ") ? message.substring("[Phantasmon] ".length()) : message;
	}

	protected static int argb(int rgb, float alpha) {
		int a = Math.max(0, Math.min(255, Math.round(alpha * 255)));
		return (a << 24) | (rgb & 0xFFFFFF);
	}

	protected static int withAlpha(int argbColor, float factor) {
		int a = Math.round(((argbColor >>> 24) & 0xFF) * Math.max(0f, Math.min(1f, factor)));
		return (a << 24) | (argbColor & 0xFFFFFF);
	}

	protected static int lerpColor(int from, int to, float t) {
		int r = Math.round(((from >> 16) & 0xFF) + (((to >> 16) & 0xFF) - ((from >> 16) & 0xFF)) * t);
		int gr = Math.round(((from >> 8) & 0xFF) + (((to >> 8) & 0xFF) - ((from >> 8) & 0xFF)) * t);
		int b = Math.round((from & 0xFF) + ((to & 0xFF) - (from & 0xFF)) * t);
		return (r << 16) | (gr << 8) | b;
	}


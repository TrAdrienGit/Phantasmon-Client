	protected enum SlotLook { NORMAL, HOVER, SELECTED, DRAG_SOURCE }

	/**
	 * Where things go inside one slot, relative to its top-left corner: the
	 * model area (scissored), the name baseline and the held-item icon.
	 */
	protected record SlotLayout(int modelTop, int modelHeight, float modelScale, int nameY, int itemX, int itemY, int itemSize) {
	}

	/** Trade rail slot (Z08, 85×214): models ×1.5 the spec's 72 px icon, name pushed under them. */
	protected static final SlotLayout RAIL_SLOT = new SlotLayout(18, 142, SLOT_MODEL_SCALE, 164, 59, 188, 20);

	/**
	 * One Pokémon slot: gender + level on top, live 3D model, name (★ if
	 * shiny), held item. Empty slots keep the normal look (trade spec §6.2);
	 * a drag source keeps its frame but hides its content (the model follows
	 * the cursor instead).
	 */
	protected void renderSlot(GuiGraphics g, int x, int y, int w, int h, PokemonDto pokemon, SlotLook look, SlotLayout layout) {
		switch (look) {
			case SELECTED -> {
				g.fill(x, y, x + w, y + h, SLOT_SELECTED_BG);
				glowInside(g, x, y, w, h, 0x50E6FF, 0.35f, 7);
				outline(g, x, y, w, h, WHITE);
			}
			case HOVER -> {
				g.fill(x, y, x + w, y + h, SLOT_HOVER_BG);
				outline(g, x, y, w, h, CYAN);
			}
			case DRAG_SOURCE -> {
				g.fill(x, y, x + w, y + h, SLOT_BG);
				glowInside(g, x, y, w, h, 0x50E6FF, 0.2f, 4);
				outline(g, x, y, w, h, CYAN2);
			}
			default -> {
				g.fill(x, y, x + w, y + h, SLOT_BG);
				outline(g, x, y, w, h, SLOT_BORDER);
			}
		}
		if (pokemon == null || look == SlotLook.DRAG_SOURCE) {
			return;
		}
		Look info = Look.of(pokemon);

		drawGender(g, info.gender(), x + 6, y + 6, 1f);
		String level = Component.translatable("phantasmon.trade.screen.level_short", pokemon.level()).getString();
		drawText(g, level, x + w - 6 - textWidth(level, 1f, false, 0f), y + 6, 1f, SLOT_TOP, false, 0f);

		int modelTop = y + layout.modelTop();
		g.flush();
		enableCanvasScissor(g, x + 1, modelTop, w - 2, layout.modelHeight());
		PokemonGuiRendering.renderModel(g, pokemon.species(), pokemon.form(), pokemon.isShiny(), PokemonGuiRendering.storedGender(pokemon),
				x + w / 2f, slotModelAnchorY(modelTop + layout.modelHeight() / 2f, layout.modelScale()), layout.modelScale());
		g.disableScissor();

		String starPrefix = pokemon.isShiny() ? "★ " : "";
		float starWidth = textWidth(starPrefix, 1f, true, 0f);
		String name = fitText(displayName(pokemon), w - 10 - starWidth, 1f, true, 0f);
		float nameStart = x + (w - starWidth - textWidth(name, 1f, true, 0f)) / 2f;
		if (!starPrefix.isEmpty()) {
			drawText(g, starPrefix, nameStart, y + layout.nameY(), 1f, STAR, true, 0f);
		}
		drawText(g, name, nameStart + starWidth, y + layout.nameY(), 1f, WHITE, true, 0f);

		ItemStack item = heldItem(pokemon);
		if (!item.isEmpty()) {
			PokemonGuiRendering.renderItemIcon(g, item, x + layout.itemX(), y + layout.itemY(), layout.itemSize());
		}
	}

	/** A slot model's anchor: same centering as the rail slots, with the confirmed offset scaled to this model's size. */
	protected static float slotModelAnchorY(float boxCenterY, float outerScale) {
		return modelAnchorY(boxCenterY, outerScale, SLOT_MODEL_OFFSET * outerScale / SLOT_MODEL_SCALE);
	}

	/** Anchor that puts the model's visual center on {@code boxCenterY} — see {@link #MODEL_CENTER_K}. */
	protected static float modelAnchorY(float boxCenterY, float outerScale, float offset) {
		return boxCenterY - MODEL_CENTER_K * outerScale + offset;
	}


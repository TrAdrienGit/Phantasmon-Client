	/** Everything a card/slot needs from Cobblemon's local data for one Pokémon, resolved once per draw. */
	protected record Look(List<ElementalType> types, ElementalType teraType, PokemonGender gender) {

		static Look of(PokemonDto pokemon) {
			Species species = PokemonSpecies.INSTANCE.getByName(pokemon.species());
			FormData form = species == null ? null : formOf(species, pokemon.form());
			List<ElementalType> types = new java.util.ArrayList<>();
			ElementalType primary = form != null ? form.getPrimaryType() : species != null ? species.getPrimaryType() : null;
			ElementalType secondary = form != null ? form.getSecondaryType() : species != null ? species.getSecondaryType() : null;
			if (primary != null) {
				types.add(primary);
			}
			if (secondary != null) {
				types.add(secondary);
			}
			Map<String, Object> data = pokemon.data() != null ? pokemon.data() : Map.of();
			Object teraRaw = data.get("tera_type");
			// Every Pokémon has an inherent Tera Type (its own primary type) until changed.
			ElementalType tera = teraRaw != null ? safeType(teraRaw.toString()) : primary;
			Float maleRatio = form != null ? Float.valueOf(form.getMaleRatio()) : species != null ? Float.valueOf(species.getMaleRatio()) : null;
			return new Look(types, tera, PokemonGender.resolve(data.get("gender"), maleRatio));
		}

		private static FormData formOf(Species species, String formId) {
			FormData form = PokemonGuiRendering.resolveForm(species, formId);
			return form != null ? form : species.getStandardForm();
		}


		static ElementalType safeType(String typeId) {
			if (typeId == null) {
				return null;
			}
			try {
				return ElementalTypes.INSTANCE.get(typeId.toLowerCase(Locale.ROOT));
			} catch (Exception ex) {
				return null;
			}
		}
	}


	@Override
	public void render(GuiGraphics graphics, int mouseX, int mouseY, float partialTick) {
		LiveTradeState state = controller.state();
		// Now that the menu no longer fills the screen, the (blurred, dimmed) game shows around it.
		super.renderBackground(graphics, mouseX, mouseY, partialTick);
		if (state == null) {
			return;
		}
		if (state.phase() == LiveTradeState.Phase.COMPLETED && completedAt < 0) {
			completedAt = System.currentTimeMillis();
			quitConfirmOpen = false;
		}
		boolean modalOpen = quitConfirmOpen || state.phase() == LiveTradeState.Phase.COMPLETED;
		double mx = modalOpen ? -1 : toCanvasX(mouseX);
		double my = modalOpen ? -1 : toCanvasY(mouseY);

		PoseStack pose = graphics.pose();
		pose.pushPose();
		pose.translate(originX, originY, 0);
		pose.scale(scale, scale, 1f);

		renderRootPanel(graphics);
		renderHeader(graphics, state, mx, my);
		renderRail(graphics, state, 0, mx, my);
		renderRail(graphics, state, RIGHT_RAIL_OFFSET, mx, my);
		renderCard(graphics, state, 0);
		renderCard(graphics, state, RIGHT_CARD_OFFSET);
		renderFooter(graphics, state, mx, my);
		pose.popPose();

		if (state.phase() == LiveTradeState.Phase.COMPLETED) {
			renderTradeModal(graphics, state, mouseX, mouseY);
		} else if (quitConfirmOpen) {
			renderQuitModal(graphics, mouseX, mouseY);
		}
	}

	/** Z01: translucent fill, 2 px cyan border + 1 px inner line, the two neon bars across the top edge. */
	private void renderRootPanel(GuiGraphics g) {
		blitTexture(g, TEX_BACKGROUND, 0, 0, CANVAS_W, CANVAS_H);
		g.fill(0, 0, CANVAS_W, CANVAS_H, PANEL_FILL);
		g.fill(0, 0, CANVAS_W, 2, PANEL_BORDER);
		g.fill(0, CANVAS_H - 2, CANVAS_W, CANVAS_H, PANEL_BORDER);
		g.fill(0, 2, 2, CANVAS_H - 2, PANEL_BORDER);
		g.fill(CANVAS_W - 2, 2, CANVAS_W, CANVAS_H - 2, PANEL_BORDER);
		g.renderOutline(2, 2, CANVAS_W - 4, CANVAS_H - 4, PANEL_INNER);
		int barWidth = Math.round(CANVAS_W * 0.34f);
		for (int barX : new int[] { 0, CANVAS_W - barWidth }) {
			g.fillGradient(barX, -15, barX + barWidth, -2, 0x0050E6FF, 0x5550E6FF);
			g.fill(barX, -2, barX + barWidth, 2, CYAN);
			g.fillGradient(barX, 2, barX + barWidth, 15, 0x5550E6FF, 0x0050E6FF);
		}
	}


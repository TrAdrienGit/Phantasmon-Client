	/** Nickname if set, else Cobblemon's localized species name, else the raw id capitalized. Public: also used for the trade chat summary. */
	public static String displayName(PokemonDto pokemon) {
		Object nickname = pokemon.data() == null ? null : pokemon.data().get("nickname");
		if (nickname != null && !nickname.toString().isBlank()) {
			return nickname.toString();
		}
		Species species = PokemonSpecies.INSTANCE.getByName(pokemon.species());
		if (species != null) {
			return species.getTranslatedName().getString();
		}
		String id = pokemon.species() == null ? "?" : pokemon.species();
		return id.isEmpty() ? id : id.substring(0, 1).toUpperCase(Locale.ROOT) + id.substring(1);
	}

	private static ItemStack heldItem(PokemonDto pokemon) {
		Object raw = pokemon.data() == null ? null : pokemon.data().get("heldItem");
		return raw == null ? ItemStack.EMPTY : PokemonGuiRendering.heldItemStack(raw.toString());
	}

	/** Same localization path as the PC detail panel ({@link AbilityTemplate#getDisplayName()} is a raw translation key). */
	private static String abilityLabel(String abilityId) {
		if (abilityId == null) {
			return "?";
		}
		AbilityTemplate template = Abilities.get(abilityId);
		return template != null ? Component.translatable(template.getDisplayName()).getString() : abilityId;
	}

	/** Everything a card/slot needs from Cobblemon's local data for one Pokémon, resolved once per draw. */
	private record Look(List<ElementalType> types, ElementalType teraType, PokemonGender gender) {

		static Look of(PokemonDto pokemon) {
			Species species = PokemonSpecies.INSTANCE.getByName(pokemon.species());
			FormData form = species == null ? null : formOf(species, pokemon.form());
			List<ElementalType> types = new java.util.ArrayList<>();
			ElementalType primary = form != null ? form.getPrimaryType() : species != null ? species.getPrimaryType() : null;
			ElementalType secondary = form != null ? form.getSecondaryType() : species != null ? species.getSecondaryType() : null;
			if (primary != null) {
				types.add(primary);
			}
			if (secondary != null) {
				types.add(secondary);
			}
			Map<String, Object> data = pokemon.data() != null ? pokemon.data() : Map.of();
			Object teraRaw = data.get("teraType");
			// Every Pokémon has an inherent Tera Type (its own primary type) until changed — same rule as the PC.
			ElementalType tera = teraRaw != null ? safeType(teraRaw.toString()) : primary;
			Float maleRatio = form != null ? Float.valueOf(form.getMaleRatio()) : species != null ? Float.valueOf(species.getMaleRatio()) : null;
			return new Look(types, tera, PokemonGender.resolve(data.get("gender"), maleRatio));
		}

		private static FormData formOf(Species species, String formId) {
			if (formId != null && !formId.isBlank()) {
				String wanted = formId.toLowerCase(Locale.ROOT);
				for (FormData form : species.getForms()) {
					if (wanted.equals(form.getName().toLowerCase(Locale.ROOT)) || wanted.equals(form.formOnlyShowdownId())) {
						return form;
					}
				}
			}
			return species.getStandardForm();
		}

		private static ElementalType safeType(String typeId) {
			try {
				return ElementalTypes.INSTANCE.get(typeId.toLowerCase(Locale.ROOT));
			} catch (Exception ex) {
				return null;
			}
		}
	}


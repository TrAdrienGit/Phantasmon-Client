	/** Stretched blit with blending on — flushes the pending fill/text batch first so code order stays draw order (see class javadoc). */
	private static void blitTexture(GuiGraphics g, Texture texture, int x, int y, int w, int h) {
		g.flush();
		RenderSystem.enableBlend();
		RenderSystem.defaultBlendFunc();
		g.blit(texture.location(), x, y, w, h, 0f, 0f, texture.width(), texture.height(), texture.width(), texture.height());
		RenderSystem.disableBlend();
	}

	/** Approximates a CSS outer {@code box-shadow} glow with fading 1 px rings. */
	private static void glowOutside(GuiGraphics g, int x, int y, int w, int h, int rgb, float alpha, int size) {
		for (int i = 1; i <= size; i++) {
			float falloff = 1f - (i - 1) / (float) size;
			g.renderOutline(x - i, y - i, w + 2 * i, h + 2 * i, argb(rgb, alpha * falloff * falloff));
		}
	}

	/** Same for an {@code inset} glow (selected slot). */
	private static void glowInside(GuiGraphics g, int x, int y, int w, int h, int rgb, float alpha, int size) {
		for (int i = 1; i <= size; i++) {
			float falloff = 1f - (i - 1) / (float) size;
			g.renderOutline(x + i, y + i, w - 2 * i, h - 2 * i, argb(rgb, alpha * falloff * falloff));
		}
	}


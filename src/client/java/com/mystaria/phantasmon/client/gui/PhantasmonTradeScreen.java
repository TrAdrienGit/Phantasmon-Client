/**
 * Live trade screen (Adrien 2026-10-02), a faithful port of the handoff
 * mock-up {@code phantasmon_trade_ui.html} / {@code SPEC_ECRAN_ECHANGE.md}.
 *
 * <p><b>Coordinates</b>: everything is laid out directly in the mock-up's own
 * 1600×900 px space — every number below is the spec's "px" column (zones
 * Z01-Z29) used verbatim. The canvas is then drawn through one pose scale of
 * {@code s/2} GUI units per px, with {@code s = min(1, width/800, height/450)}
 * (spec §2): at 1080p / GUI scale 2 one mock-up px is exactly one screen pixel,
 * so the zones line up with the reference capture; at any other scale the
 * canvas shrinks uniformly and stays centered. Mouse positions are converted
 * back with {@link #toCanvasX}/{@link #toCanvasY} before any hit test.
 *
 * <p><b>Text</b>: Minecraft's font only stays crisp at integer scales, so the
 * mock-up's 16px titles use scale 2 (one font pixel = 2 px) and every smaller
 * size scale 1 (spec §9: "privilégier les échelles 1 et 0,5" in GUI units).
 *
 * <p><b>Draw order</b>: in 1.21.1 {@code fill}/{@code drawString} are batched
 * while {@code blit} draws immediately, so a texture blitted after a fill
 * would end up <em>under</em> it (the same pipeline surprise documented for
 * the PC screen's drop-down). {@link #blitTexture} therefore always
 * {@code flush()}es first, which keeps the code order the visual order.
 * Modal windows are drawn at z=2000, above item icons and 3D models.
 *
 * <p>Gradients/halos the vanilla GUI can't draw are the PNGs generated by
 * {@code scripts/generate_trade_textures.py} from the mock-up's exact CSS.
 * Every state shown here is the server's ({@link LiveTradeState}) — clicks
 * only send requests through {@link LiveTradeController}.
 */

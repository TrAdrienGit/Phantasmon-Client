	public static void setModelOffset(boolean card, float px) {
		if (card) {
			cardModelOffset = px;
		} else {
			slotModelOffset = px;
		}
	}

	public static float modelOffset(boolean card) {
		return card ? cardModelOffset : slotModelOffset;
	}


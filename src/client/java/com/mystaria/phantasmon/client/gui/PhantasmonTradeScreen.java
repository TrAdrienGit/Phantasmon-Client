	/** Same badge with its text at {@code textScale} (2 for the enlarged Téracristal value); height grows with it. */
	private int drawTypeBadge(GuiGraphics g, ElementalType type, float xf, float yf, float textScale) {
		int x = Math.round(xf);
		int y = Math.round(yf);
		String label = upper(type.getDisplayName().getString());
		int w = typeBadgeWidth(type, textScale);
		int h = Math.round(7 * textScale) + 12;
		int bg = type.getPrimaryColor() | 0xFF000000;
		g.fill(x + 1, y + 1, x + w - 1, y + h - 1, bg);
		g.fill(x + 1, y, x + w - 1, y + 1, BADGE_BORDER);
		g.fill(x + 1, y + h - 1, x + w - 1, y + h, BADGE_BORDER);
		g.fill(x, y + 1, x + 1, y + h - 1, BADGE_BORDER);
		g.fill(x + w - 1, y + 1, x + w, y + h - 1, BADGE_BORDER);
		drawText(g, label, x + 8, y + 6, textScale, 0xFF000000 | PokemonGuiRendering.readableTextColor(bg), true, 0.5f);
		return w;
	}

	private int typeBadgeWidth(ElementalType type, float textScale) {
		return Math.round(textWidth(upper(type.getDisplayName().getString()), textScale, true, 0.5f)) + 16;
	}

	private void drawGender(GuiGraphics g, PokemonGender gender, float x, float y, float textScale) {
		if (gender == PokemonGender.MALE) {
			drawText(g, "♂", x, y, textScale, MALE, false, 0f);
		} else if (gender == PokemonGender.FEMALE) {
			drawText(g, "♀", x, y, textScale, FEMALE, false, 0f);
		}
	}

	private void enableCanvasScissor(GuiGraphics g, int x, int y, int w, int h) {
		g.enableScissor(
				Math.round(originX + x * scale), Math.round(originY + y * scale),
				Math.round(originX + (x + w) * scale), Math.round(originY + (y + h) * scale));
	}

	private void drawCentered(GuiGraphics g, String text, float centerX, float y, float textScale, int color, boolean bold, float spacing) {
		drawText(g, text, centerX - textWidth(text, textScale, bold, spacing) / 2f, y, textScale, color, bold, spacing);
	}

	/** Draws {@code text} with its glyph top at {@code y}, optionally with CSS-like {@code letter-spacing} (canvas px). */
	private void drawText(GuiGraphics g, String text, float x, float y, float textScale, int color, boolean bold, float spacing) {
		if (text == null || text.isEmpty() || (color >>> 24) < 8) {
			return;
		}
		PoseStack pose = g.pose();
		pose.pushPose();
		pose.translate(x, y, 0);
		pose.scale(textScale, textScale, 1f);
		if (spacing <= 0f) {
			g.drawString(font, styled(text, bold), 0, 0, color, false);
		} else {
			float cursor = 0f;
			int i = 0;
			while (i < text.length()) {
				int codePoint = text.codePointAt(i);
				String glyph = new String(Character.toChars(codePoint));
				pose.pushPose();
				pose.translate(cursor, 0, 0);
				g.drawString(font, styled(glyph, bold), 0, 0, color, false);
				pose.popPose();
				cursor += font.width(styled(glyph, bold)) + spacing / textScale;
				i += Character.charCount(codePoint);
			}
		}
		pose.popPose();
	}

	private void drawSequence(GuiGraphics g, FormattedCharSequence sequence, float x, float y, int color) {
		PoseStack pose = g.pose();
		pose.pushPose();
		pose.translate(x, y, 0);
		g.drawString(font, sequence, 0, 0, color, false);
		pose.popPose();
	}

	/** Rendered width in canvas px, letter-spacing included. */
	private float textWidth(String text, float textScale, boolean bold, float spacing) {
		if (text == null || text.isEmpty()) {
			return 0f;
		}
		int glyphs = text.codePointCount(0, text.length());
		return font.width(styled(text, bold)) * textScale + spacing * (glyphs - 1);
	}

	/** Truncates with "…" so the text fits in {@code maxWidth} canvas px (spec §6.2/§10: no overflowing text). */
	private String fitText(String text, float maxWidth, float textScale, boolean bold, float spacing) {
		if (text == null || textWidth(text, textScale, bold, spacing) <= maxWidth) {
			return text;
		}
		String ellipsis = "…";
		String result = text;
		while (!result.isEmpty() && textWidth(result + ellipsis, textScale, bold, spacing) > maxWidth) {
			result = result.substring(0, result.length() - 1);
		}
		return result.stripTrailing() + ellipsis;
	}

	private static MutableComponent styled(String text, boolean bold) {
		MutableComponent component = Component.literal(text);
		return bold ? component.withStyle(ChatFormatting.BOLD) : component;
	}

	private static String upper(String text) {
		return text == null ? "" : text.toUpperCase(Locale.ROOT);
	}

	private static String stripPrefix(String message) {
		return message.startsWith("[Phantasmon] ") ? message.substring("[Phantasmon] ".length()) : message;
	}

	private static int argb(int rgb, float alpha) {
		int a = Math.max(0, Math.min(255, Math.round(alpha * 255)));
		return (a << 24) | (rgb & 0xFFFFFF);
	}

	private static int withAlpha(int argbColor, float factor) {
		int a = Math.round(((argbColor >>> 24) & 0xFF) * Math.max(0f, Math.min(1f, factor)));
		return (a << 24) | (argbColor & 0xFFFFFF);
	}

	private static int lerpColor(int from, int to, float t) {
		int r = Math.round(((from >> 16) & 0xFF) + (((to >> 16) & 0xFF) - ((from >> 16) & 0xFF)) * t);
		int gr = Math.round(((from >> 8) & 0xFF) + (((to >> 8) & 0xFF) - ((from >> 8) & 0xFF)) * t);
		int b = Math.round((from & 0xFF) + ((to & 0xFF) - (from & 0xFF)) * t);
		return (r << 16) | (gr << 8) | b;
	}


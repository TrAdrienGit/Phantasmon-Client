package com.mystaria.phantasmon.client.battle;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.UUID;

import com.google.gson.FieldNamingPolicy;
import com.google.gson.Gson;
import com.google.gson.GsonBuilder;

import com.mystaria.phantasmon.client.pokemon.PokemonDto;

/**
 * The battle lobby as the backend shows it to this player ({@code BattleLobbyUpdated}): our own team in full with
 * our lead, the opponent's team as a preview only (species, form, shininess, gender — what the model shows) and
 * whether they are ready. Their lead is never sent. Everything here is the server's; the screen only reads it.
 */
public final class BattleLobbyState {

	public static final int TEAM_SIZE = 6;
	private static final Gson GSON = new GsonBuilder().setFieldNamingPolicy(FieldNamingPolicy.LOWER_CASE_WITH_UNDERSCORES).create();

	private final UUID lobbyUuid;
	private UUID opponentUuid;
	private String opponentName = "?";
	private String ownSource = "GHOST";
	private String opponentSource = "GHOST";
	private List<PokemonDto> ownTeam = List.of();
	private List<PokemonDto> opponentTeam = List.of();
	private int ownLead;
	/** Our leads in slot order: one, or two in doubles (left, then right). */
	private List<Integer> ownLeads = List.of(0);
	private boolean doubles;
	/** Pokémon picked one by one in order: doubles, and singles formats sending only some (BSS: 3 of 6). */
	private boolean pickMode;
	/** Showdown generates both teams at the start (random formats): nothing to pick. */
	private boolean randomTeam;
	/** Random format: false while the opponent's generated team has not reached the backend. */
	private boolean opponentTeamGenerated = true;
	/** Doubles: the Pokémon we picked, in order (1 and 2 lead, left then right). */
	private List<Integer> ownPicks = List.of();
	/** Pokémon that go into the battle (VGC: 4 of 6). */
	private int battleSize = TEAM_SIZE;
	private boolean ownReady;
	private boolean opponentReady;
	private int timerTotalSeconds = 150;
	/** Local clock deadline of the lobby timer, 0 while off. */
	private long timerDeadline;
	private String timerByName;
	private String lastErrorCode;

	/** Battle format (TODO-24): offered ones (id, name), the picked one, what breaks it. */
	/**
	 * A format of the picker (2026-11-27): {@code column} SINGLES / DOUBLES / RANDOM / OTHER; its tags (National Dex,
	 * Champions, teams generated by Showdown, level, Pokémon sent out of the team).
	 */
	public record FormatOption(String id, String name, boolean doubles, String column, boolean natDex, boolean champions,
			boolean randomTeam, int adjustLevel, int pickedTeamSize, int maxTeamSize) {

		public FormatOption(String id, String name, boolean doubles) {
			this(id, name, doubles, doubles ? "DOUBLES" : "SINGLES", false, false, false, 0, 0, 6);
		}
	}

	public record Issue(String code, String subject) {
	}

	private List<FormatOption> formats = List.of();
	private String formatId = "free";
	/** The battle ambiance both see (Showtime A3): an ambiance id, or "" for each player's own. */
	private String ambiance = "";
	/** The intro both see: a Showtime intro name, or "" for each player's own choice. */
	private String intro = "";
	/** An event NPC imposes the ambiance / the intro (2026-11-18): the drop-down is locked. */
	private boolean ambianceFixed;
	private boolean introFixed;
	/**
	 * The battle field (League Reborn, 2026-11-18): a field id or "" for none; locked for us (an event NPC's, or laid
	 * down by the opponent); the ones we may lay down (a gym leader's rewards, every one for an admin).
	 */
	private String field = "";
	private boolean fieldFixed;
	private List<String> fields = List.of();
	/** A tournament match's or an event NPC's format: the drop-down is locked. */
	private boolean formatFixed;
	private List<List<Issue>> ownIssues = List.of();
	private List<Boolean> opponentFlags = List.of();

	BattleLobbyState(UUID lobbyUuid) {
		this.lobbyUuid = lobbyUuid;
	}

	void apply(Map<String, Object> data) {
		opponentUuid = parseUuid(data.get("opponent_uuid"));
		opponentName = data.get("opponent_name") == null ? "?" : data.get("opponent_name").toString();
		ownSource = String.valueOf(data.get("own_team_source"));
		opponentSource = String.valueOf(data.get("opponent_team_source"));
		ownTeam = ownTeam(data.get("own_team"));
		opponentTeam = preview(data.get("opponent_team"));
		ownLead = data.get("own_lead") instanceof Number lead ? lead.intValue() : 0;
		doubles = "doubles".equals(data.get("game_type"));
		pickMode = data.get("pick_mode") instanceof Boolean mode ? mode : doubles;
		randomTeam = Boolean.TRUE.equals(data.get("random_team"));
		opponentTeamGenerated = !Boolean.FALSE.equals(data.get("opponent_team_generated"));
		List<Integer> leads = new ArrayList<>();
		if (data.get("own_leads") instanceof List<?> list) {
			list.forEach(index -> {
				if (index instanceof Number number) {
					leads.add(number.intValue());
				}
			});
		}
		ownLeads = leads.isEmpty() ? List.of(ownLead) : List.copyOf(leads);
		List<Integer> picks = new ArrayList<>();
		if (data.get("own_picks") instanceof List<?> list) {
			list.forEach(index -> {
				if (index instanceof Number number) {
					picks.add(number.intValue());
				}
			});
		}
		ownPicks = List.copyOf(picks);
		battleSize = data.get("battle_size") instanceof Number size ? size.intValue() : TEAM_SIZE;
		ownReady = Boolean.TRUE.equals(data.get("own_ready"));
		opponentReady = Boolean.TRUE.equals(data.get("opponent_ready"));
		if (data.get("timer_total_seconds") instanceof Number total) {
			timerTotalSeconds = total.intValue();
		}
		timerDeadline = data.get("timer_seconds_left") instanceof Number left ? System.currentTimeMillis() + left.longValue() * 1000L : 0;
		timerByName = data.get("timer_by_name") == null ? null : data.get("timer_by_name").toString();
		lastErrorCode = null;
		if (data.get("format_id") != null) {
			formatId = data.get("format_id").toString();
		}
		ambiance = data.get("ambiance") == null ? "" : data.get("ambiance").toString();
		intro = data.get("intro") == null ? "" : data.get("intro").toString();
		ambianceFixed = Boolean.TRUE.equals(data.get("ambiance_fixed"));
		introFixed = Boolean.TRUE.equals(data.get("intro_fixed"));
		formatFixed = Boolean.TRUE.equals(data.get("format_fixed"));
		field = data.get("field") == null ? "" : data.get("field").toString();
		fieldFixed = Boolean.TRUE.equals(data.get("field_fixed"));
		fields = data.get("fields") instanceof List<?> ids ? ids.stream().map(String::valueOf).toList() : List.of();
		if (data.get("formats") instanceof List<?> list) {
			formats = parseFormats(list);
		}
		List<List<Issue>> issues = new ArrayList<>();
		if (data.get("own_team_issues") instanceof List<?> perMember) {
			for (Object member : perMember) {
				List<Issue> own = new ArrayList<>();
				if (member instanceof List<?> entries) {
					for (Object entry : entries) {
						if (entry instanceof Map<?, ?> map) {
							own.add(new Issue(String.valueOf(map.get("code")), String.valueOf(map.get("subject"))));
						}
					}
				}
				issues.add(own);
			}
		}
		ownIssues = issues;
		List<Boolean> flags = new ArrayList<>();
		if (data.get("opponent_team_flags") instanceof List<?> list) {
			list.forEach(flag -> flags.add(Boolean.TRUE.equals(flag)));
		}
		opponentFlags = flags;
	}

	/** Kept in the backend's order: lead indexes refer to it. */
	private static List<PokemonDto> ownTeam(Object raw) {
		List<PokemonDto> team = new ArrayList<>();
		if (raw instanceof List<?> list) {
			for (Object entry : list) {
				PokemonDto pokemon = GSON.fromJson(GSON.toJsonTree(entry), PokemonDto.class);
				if (pokemon != null) {
					team.add(pokemon);
				}
			}
		}
		return team;
	}

	/** The opponent's preview, as Pokémon with nothing but what the model needs (level 0, no set, no item). */
	private static List<PokemonDto> preview(Object raw) {
		List<PokemonDto> team = new ArrayList<>();
		if (raw instanceof List<?> list) {
			for (Object entry : list) {
				if (entry instanceof Map<?, ?> map && map.get("species") != null) {
					Map<String, Object> data = new HashMap<>();
					if (map.get("gender") != null) {
						data.put("gender", map.get("gender"));
					}
					team.add(new PokemonDto(null, null, map.get("species").toString(),
							map.get("form") == null ? null : map.get("form").toString(), 0, null, null,
							Boolean.TRUE.equals(map.get("is_shiny")), null, null, null, null, data));
				}
			}
		}
		return team;
	}

	private static UUID parseUuid(Object raw) {
		try {
			return raw == null ? null : UUID.fromString(raw.toString());
		} catch (IllegalArgumentException ex) {
			return null;
		}
	}

	public UUID lobbyUuid() {
		return lobbyUuid;
	}

	public UUID opponentUuid() {
		return opponentUuid;
	}

	public String opponentName() {
		return opponentName;
	}

	public boolean ownIsCobblemon() {
		return "COBBLEMON".equals(ownSource);
	}

	public boolean opponentIsCobblemon() {
		return "COBBLEMON".equals(opponentSource);
	}

	public PokemonDto ownSlot(int index) {
		return index >= 0 && index < ownTeam.size() ? ownTeam.get(index) : null;
	}

	public PokemonDto opponentSlot(int index) {
		return index >= 0 && index < opponentTeam.size() ? opponentTeam.get(index) : null;
	}

	public int opponentTeamSize() {
		return opponentTeam.size();
	}

	public int ownTeamSize() {
		return ownTeam.size();
	}

	public int ownLead() {
		return ownLead;
	}

	public PokemonDto ownLeadPokemon() {
		return ownSlot(ownLead);
	}

	/** Our leads in slot order: one, or two in doubles (left, then right). */
	public List<Integer> ownLeads() {
		return ownLeads;
	}

	/** The lead slot of team member {@code index} (0 left, 1 right), or -1. */
	public int ownLeadSlot(int index) {
		return ownLeads.indexOf(index);
	}

	/** Doubles: the Pokémon we picked, in order. */
	public List<Integer> ownPicks() {
		return ownPicks;
	}

	/** Doubles: this team slot's place in our picks (1 = left lead, 2 = right lead, 3+ = bench), 0 = not picked. */
	public int ownPickNumber(int index) {
		return ownPicks.indexOf(index) + 1;
	}

	/** Pokémon that go into the battle (VGC: 4 of 6; else the whole team). */
	public int battleSize() {
		return battleSize;
	}

	/** The picked format is a doubles one: two leads. */
	public boolean doubles() {
		return doubles;
	}

	/** Pokémon are picked one by one in order (doubles, "pick n" formats), else a single lead is chosen. */
	public boolean pickMode() {
		return pickMode;
	}

	/** A random format: the players' teams are not used. */
	/** Random format: false while one of the two teams is still being generated, "Ready" waits for both. */
	public boolean teamsGenerated() {
		return !randomTeam || ownTeamSize() > 0 && opponentTeamGenerated;
	}

	public boolean ownTeamGenerated() {
		return !randomTeam || ownTeamSize() > 0;
	}

	public boolean randomTeam() {
		return randomTeam;
	}

	/** The backend's format entries (lobby update, {@code GET /battles/formats}) as picker options. */
	public static List<FormatOption> parseFormats(List<?> list) {
		List<FormatOption> options = new ArrayList<>();
		for (Object entry : list) {
			if (entry instanceof Map<?, ?> map && map.get("id") != null) {
				boolean twin = "doubles".equals(map.get("game_type"));
				options.add(new FormatOption(map.get("id").toString(), String.valueOf(map.get("name")), twin,
						map.get("column") == null ? (twin ? "DOUBLES" : "SINGLES") : map.get("column").toString(),
						Boolean.TRUE.equals(map.get("natdex")), Boolean.TRUE.equals(map.get("champions")),
						Boolean.TRUE.equals(map.get("random_team")), number(map.get("adjust_level"), 0),
						number(map.get("picked_team_size"), 0), number(map.get("max_team_size"), 6)));
			}
		}
		return options;
	}

	private static int number(Object value, int fallback) {
		return value instanceof Number number ? number.intValue() : fallback;
	}

	public boolean ownReady() {
		return ownReady;
	}

	public boolean opponentReady() {
		return opponentReady;
	}

	public boolean timerOn() {
		return timerDeadline > 0;
	}

	public int timerTotalSeconds() {
		return timerTotalSeconds;
	}

	public long timerSecondsLeft() {
		return timerDeadline <= 0 ? 0 : Math.max(0, (timerDeadline - System.currentTimeMillis() + 999) / 1000);
	}

	public String timerByName() {
		return timerByName;
	}

	public List<FormatOption> formats() {
		return formats;
	}

	public String ambiance() {
		return ambiance;
	}

	public String intro() {
		return intro;
	}

	public boolean ambianceFixed() {
		return ambianceFixed;
	}

	public boolean introFixed() {
		return introFixed;
	}

	public String field() {
		return field;
	}

	public boolean fieldFixed() {
		return fieldFixed;
	}

	public List<String> fields() {
		return fields;
	}

	public boolean formatFixed() {
		return formatFixed;
	}

	public String formatId() {
		return formatId;
	}

	public FormatOption format() {
		return formats.stream().filter(option -> option.id().equals(formatId)).findFirst()
				.orElse(new FormatOption(formatId, formatId, doubles));
	}

	/** What our Pokémon at {@code index} breaks in the picked format (empty = fine). */
	public List<Issue> ownIssues(int index) {
		return index >= 0 && index < ownIssues.size() ? ownIssues.get(index) : List.of();
	}

	public boolean ownTeamBreaksRules() {
		return ownIssues.stream().anyMatch(list -> !list.isEmpty());
	}

	/** Whether the opponent's Pokémon at {@code index} breaks the format (circled in red, reason not known). */
	public boolean opponentFlagged(int index) {
		return index >= 0 && index < opponentFlags.size() && opponentFlags.get(index);
	}

	public String lastErrorCode() {
		return lastErrorCode;
	}

	void setLastErrorCode(String errorCode) {
		lastErrorCode = errorCode;
	}
}

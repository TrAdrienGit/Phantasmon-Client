"""
Writes src/main/resources/assets/phantasmon/showdown/new_megas_data.js: the Mega Evolutions added after the battle
engine Cobblemon bundles (Legends Z-A / Champions), taken from Pokémon Showdown's source at a pinned commit (MIT,
Copyright (c) 2011-2026 Guangcong Luo and other contributors).

    python tools/new_megas.py [showdown checkout]

Without a checkout, the four files it reads are downloaded from GitHub at COMMIT. To follow a newer Showdown, change
COMMIT, run it, then run the engine test (tools/new_megas_test.js).

What it takes: every Mega forme whose Mega Stone is marked "Future", that stone, and the "Future" abilities
those formes have (their code, as Showdown wrote it). The installer (new_megas.js) adapts what the bundled engine lacks.
"""
import re
import sys
import urllib.request
from pathlib import Path

COMMIT = "c7fa6f16503de510c319239b5b2d29d4f7abd8c4"  # smogon/pokemon-showdown master, 2026-11-25
ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src/main/resources/assets/phantasmon/showdown/new_megas_data.js"


def read(checkout, path):
    if checkout:
        return (Path(checkout) / path).read_text(encoding="utf-8")
    url = f"https://raw.githubusercontent.com/smogon/pokemon-showdown/{COMMIT}/{path}"
    with urllib.request.urlopen(url) as response:
        return response.read().decode("utf-8")


def entries(source):
    """Top-level entries of a Showdown data table: id -> its source text ("{ ... }")."""
    found = {}
    for match in re.finditer(r"^\t([a-z0-9]+): \{\n(.*?)^\t\},$", source, re.M | re.S):
        found[match.group(1)] = "{\n" + match.group(2) + "\t}"
    return found


def field(text, name):
    match = re.search(r"^\t\t" + name + r": (.*?),$", text, re.M)
    return match.group(1) if match else None


def strip_future(text):
    return re.sub(r"^\t\tisNonstandard: \"Future\",\n", "", text, flags=re.M)


def strip_types(text):
    """The TypeScript left in ability code: casts."""
    return re.sub(r" as (?:ID|any)\b", "", text)


def without_functions(text):
    """An item's data without its handlers (the installer gives Mega Stones their own onTakeItem)."""
    lines, out, depth = text.split("\n"), [], 0
    for line in lines:
        if depth == 0 and re.match(r"^\t\t[a-zA-Z]+\(.*\) \{$", line):
            depth = 1
            continue
        if depth:
            depth += line.count("{") - line.count("}")
            continue
        out.append(line)
    return "\n".join(out)


def to_id(name):
    return re.sub(r"[^a-z0-9]", "", name.lower())


def main():
    checkout = sys.argv[1] if len(sys.argv) > 1 else None
    pokedex = entries(read(checkout, "data/pokedex.ts"))
    items = entries(read(checkout, "data/items.ts"))
    abilities = entries(read(checkout, "data/abilities.ts"))

    # The new formes: Megas whose stone is "Future" (pokedex.ts doesn't mark them, formats-data.ts does).
    def future_stone(text):
        stone = field(text, "requiredItem")
        return stone and 'isNonstandard: "Future"' in items.get(to_id(stone.strip('"')), "")
    species = {k: v for k, v in pokedex.items() if "Mega" in (field(v, "forme") or "") and future_stone(v)}
    stones = sorted({to_id(field(v, "requiredItem").strip('"')) for v in species.values()})
    used = set()
    for text in species.values():
        used.update(to_id(n) for n in re.findall(r'"([^"]+)"', field(text, "abilities") or ""))
    new_abilities = sorted(a for a in used if a in abilities and 'isNonstandard: "Future"' in abilities[a])

    missing = [s for s in stones if s not in items]
    if missing:
        sys.exit(f"Stones not in items.ts: {missing}")

    def table(name, ids, source, transform):
        body = ",\n".join(f"\t\t{i}: " + transform(source[i]).replace("\n", "\n\t") for i in ids)
        return f"\t{name}: {{\n{body},\n\t}},"

    text = "\n".join([
        "// GENERATED by tools/new_megas.py: never edit by hand.",
        f"// From Pokémon Showdown (https://github.com/smogon/pokemon-showdown) at {COMMIT}.",
        "// MIT License, Copyright (c) 2011-2026 Guangcong Luo and other contributors.",
        "({",
        f'\tcommit: "{COMMIT}",',
        table("species", sorted(species), species, strip_future),
        table("items", stones, items, lambda t: strip_future(without_functions(t))),
        table("abilities", new_abilities, abilities, lambda t: strip_types(strip_future(t))),
        "})",
        "",
    ])
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{len(species)} formes, {len(stones)} stones, {len(new_abilities)} abilities "
          f"({', '.join(new_abilities)}) -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
